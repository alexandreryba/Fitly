"""Excel export of the offers known to Fitly: data/Fitly_offres.xlsx.

Columns A-F as requested (Date collecte, Entreprise, Poste, Localisation, Publication, Lien fiche de poste),
then useful extras (score, role, status, source...). One sheet with every open offer, one with the relevant
ones (score >= 55). Regenerated by every morning collection and from the interface.

    python -m fitly.review.export_offers
"""

from __future__ import annotations

from datetime import date, datetime
from pathlib import Path
from typing import Any

from fitly import paths

COLUMNS = [
    "Date collecte",
    "Entreprise",
    "Poste",
    "Localisation",
    "Publication",
    "Lien fiche de poste",
    "Date de publication",
    "Score",
    "Métier",
    "Statut",
    "Source",
    "Disponibilité",
    "CV conseillé",
    "ID Fitly",
]
WIDTHS = [14, 26, 50, 30, 15, 45, 14, 8, 26, 14, 26, 24, 12, 11]
STATUS_FR = {
    "not_started": "à trier",
    "go": "GO",
    "prepared": "préparée",
    "submitted": "envoyée",
    "followed_up": "relancée",
    "interview": "entretien",
}
AVAIL_FR = {
    "open": "vérifiée",
    "closed": "expirée",
    "not_on_employer_site": "absente du site carrière",
    "no_board": "",
    None: "",
}
RELEVANT = 55


def ago(day, today=None) -> str:
    """'today', '1 day ago', '3 days ago', '2 weeks ago', '5 months ago' (LinkedIn style)."""
    if not day:
        return ""
    try:
        d = date.fromisoformat(str(day)[:10])
    except ValueError:
        return ""
    n = ((today or date.today()) - d).days
    if n <= 0:
        return "today"
    for size, unit in ((365, "year"), (30, "month"), (7, "week"), (1, "day")):
        if n >= size:
            k = n // size
            return f"{k} {unit}{'s' if k > 1 else ''} ago"
    return "today"


def rows(db_path=None) -> list[list[Any]]:
    from fitly.review import review_queue
    from fitly.ui.labels import source_label

    out = []
    for r in review_queue.build(paths.db_path(db_path)):
        published = r.get("posted_at") or ""
        out.append(
            [
                str(r.get("first_seen_at") or "")[:10],
                r["company"],
                r["title"],
                r.get("location") or "",
                ago(published or r.get("first_seen_at")),
                r["url"],
                published[:10],
                int(r.get("score") or 0),
                r.get("matched_role") or "",
                STATUS_FR.get(r["application_status"], r["application_status"]),
                source_label(r.get("source"), r.get("via")),
                AVAIL_FR.get(r.get("availability"), ""),
                r.get("recommended_cv") or "",
                r["id"],
            ]
        )
    return sorted(out, key=lambda x: (-x[7], x[0]), reverse=False)


def write(path=None, db_path=None) -> tuple[Path, int]:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill
    from openpyxl.utils import get_column_letter

    db_path = paths.db_path(db_path)
    path = Path(path or Path(db_path).parent / "Fitly_offres.xlsx")
    data = rows(db_path)
    wb = Workbook()
    sheets = [("Offres pertinentes", [r for r in data if r[7] >= RELEVANT]), ("Toutes les offres", data)]
    for i, (title, body) in enumerate(sheets):
        ws = wb.active if i == 0 else wb.create_sheet()
        ws.title = title
        ws.append(COLUMNS)
        for r in body:
            ws.append(r)
            link = ws.cell(row=ws.max_row, column=6)
            if link.value:
                link.hyperlink = link.value
                link.style = "Hyperlink"
        for c, w in enumerate(WIDTHS, 1):
            ws.column_dimensions[get_column_letter(c)].width = w
            ws.cell(row=1, column=c).font = Font(bold=True, color="FFFFFF")
            ws.cell(row=1, column=c).fill = PatternFill("solid", fgColor="1F4E78")
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions
    ws = wb.create_sheet("Infos")
    ws.append(["Généré le", datetime.now().strftime("%Y-%m-%d %H:%M")])
    ws.append(["Offres", len(data)])
    ws.append(["Pertinentes (score ≥ 55)", sum(r[7] >= RELEVANT for r in data)])
    ws.append(["Note", "Export en lecture : modifier ce fichier ne change pas Fitly. Régénéré à chaque collecte."])
    try:
        wb.save(path)
    except PermissionError:  # open in Excel: write a dated copy instead
        path = path.with_name(f"{path.stem}_{datetime.now():%Y%m%d_%H%M%S}{path.suffix}")
        wb.save(path)
    return path, len(data)


if __name__ == "__main__":
    p, n = write()
    print(f"{n} offres → {p}")
